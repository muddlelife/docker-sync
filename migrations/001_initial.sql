CREATE TABLE IF NOT EXISTS registries(id TEXT PRIMARY KEY, data TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS rules(
 id TEXT PRIMARY KEY, registry_id TEXT NOT NULL REFERENCES registries(id) ON DELETE RESTRICT,
 data TEXT NOT NULL, target TEXT NOT NULL, enabled INTEGER NOT NULL);
CREATE UNIQUE INDEX IF NOT EXISTS enabled_targets ON rules(target) WHERE enabled=1;
CREATE TABLE IF NOT EXISTS settings(id INTEGER PRIMARY KEY CHECK(id=1), data TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS tasks(
 id TEXT PRIMARY KEY, status TEXT NOT NULL, data TEXT NOT NULL, payload TEXT NOT NULL,
 connection TEXT NOT NULL, request_key TEXT UNIQUE NOT NULL, next_poll INTEGER NOT NULL DEFAULT 0);
CREATE TABLE IF NOT EXISTS task_targets(target TEXT PRIMARY KEY,task_id TEXT NOT NULL REFERENCES tasks(id));
CREATE TABLE IF NOT EXISTS attempts(
 task_id TEXT NOT NULL REFERENCES tasks(id), attempt INTEGER NOT NULL, result TEXT, logs TEXT,
 PRIMARY KEY(task_id,attempt));
CREATE TABLE IF NOT EXISTS sessions(token_hash TEXT PRIMARY KEY, csrf TEXT NOT NULL, authenticated INTEGER NOT NULL, expires INTEGER NOT NULL);
PRAGMA user_version=1;
